/**
 * Universal Multi-Language Text Selector for all 9 supported languages:
 * en, vi, fr, de, ja, zh, he, ko, es
 */
export function tMulti(
  lang: Language,
  translations: {
    en: string;
    vi: string;
    fr?: string;
    de?: string;
    ja?: string;
    zh?: string;
    he?: string;
    ko?: string;
    es?: string;
  }
): string {
  return translations[lang] || translations.fr || translations.de || translations.es || translations.en;
}

